import { describe, expect, it } from "vitest";
import { toE164 } from "../src/phone.js";

/*
 * 独立 QA（IQA-09, 2026-10-06）。抑止（DNC）は E.164 の文字列の完全一致で照合するので、
 * 同じ番号が 2 通りの E.164 になると、片方で登録した抑止がもう片方に効かない。修正されるまで RED。
 */
describe("IQA-09: 国番号の後ろの国内プレフィックス 0 を落とさない", () => {
  const canonical = toE164("090-0000-0001");

  it.each([
    "+81 (0)90-0000-0001", // 名刺・署名でよく見る表記
    "+81 090-0000-0001",
    "+81-090-0000-0001",
    "0081 090 0000 0001",
    "＋８１（０）９０－００００－０００１", // 全角
  ])("%s は 090-0000-0001 と同じ E.164 になる", (raw) => {
    expect(canonical).toEqual({ ok: true, value: "+819000000001" });
    expect(toE164(raw)).toEqual(canonical);
  });
});

/*
 * IQA-09 の修正の穴（CI の property test が発見、2026-10-09）：0 を 1 つ落とした後にまだ 0 が残る形
 * （+33 0 0…）は、1 回目の正規化で +330…、2 回目でさらに 0 が落ちて別の値（または拒否）になっていた。
 * 正規化が冪等でないと、保存した抑止の番号と照合の番号がずれうる。0 で始まる国内番号は存在しないので拒否する。
 */
describe("国番号の後ろに 0 が 2 つ以上続く番号は拒否する（正規化を冪等に保つ）", () => {
  it.each(["+330000000", "+33 0 0123 4567", "+81 0 090 0000 0001", "+810090000000"])(
    "%s は番号として受け付けない",
    (raw) => {
      expect(toE164(raw)).toEqual({ ok: false, error: "INVALID_NUMBER" });
    },
  );

  it("一度正規化した値を正規化し直しても、同じ値か同じ拒否になる", () => {
    for (const raw of ["+330000000", "+33 0 123456789", "+81 (0)90-0000-0001"]) {
      const first = toE164(raw);
      const second = first.ok ? toE164(first.value) : first;
      expect(second).toEqual(first);
    }
  });
});
